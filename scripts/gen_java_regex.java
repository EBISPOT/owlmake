    static String esc(String s) {
        StringBuilder b = new StringBuilder();
        for (char c : s.toCharArray()) {
            if (c < 0x20 || c > 0x7e || c == '\\') b.append(String.format("\\u%04x", (int) c));
            else b.append(c);
        }
        return b.toString();
    }

    static void probe(String kind, String pattern, boolean twice) {
        Pattern p;
        try {
            p = Pattern.compile(pattern);
        } catch (PatternSyntaxException e) {
            OUT.append(kind).append('\t').append(esc(pattern)).append("\tE\n");
            return;
        }
        StringBuilder bits = new StringBuilder();
        for (int i = 0; i < PROBES.length; i += 4) {
            int nibble = 0;
            for (int j = i; j < i + 4; j++) {
                boolean found = j < PROBES.length && p.matcher(twice ? PROBES[j] + PROBES[j] : PROBES[j]).find();
                nibble = nibble << 1 | (found ? 1 : 0);
            }
            bits.append(Character.forDigit(nibble, 16));
        }
        OUT.append(kind).append('\t').append(esc(pattern)).append('\t').append(bits).append('\n');
    }

    static void p(String pattern) { probe("P", pattern, false); }
    static void d(String pattern) { probe("D", pattern, true); }

    static void m(String pattern, String input) {
        OUT.append("M\t").append(esc(pattern)).append('\t').append(esc(input)).append('\t');
        Pattern p;
        try {
            p = Pattern.compile(pattern);
        } catch (PatternSyntaxException e) {
            OUT.append("E\n");
            return;
        }
        Matcher m = p.matcher(input);
        try {
            if (!m.find()) {
                OUT.append("N\n");
                return;
            }
        } catch (RuntimeException e) {
            OUT.append("X\n");
            return;
        }
        for (int g = 0; g <= m.groupCount(); g++) {
            OUT.append(g == 0 ? "" : ";");
            OUT.append(m.start(g) < 0 ? "-" : m.start(g) + "," + m.end(g));
        }
        OUT.append('\n');
    }

    static void f(String pattern, String input) {
        OUT.append("F\t").append(esc(pattern)).append('\t').append(esc(input)).append('\t');
        Pattern p;
        try {
            p = Pattern.compile(pattern);
        } catch (PatternSyntaxException e) {
            OUT.append("E\n");
            return;
        }
        Matcher m = p.matcher(input);
        StringBuilder spans = new StringBuilder();
        try {
            while (m.find()) spans.append(spans.length() == 0 ? "" : ";").append(m.start()).append(',').append(m.end());
        } catch (RuntimeException e) {
            OUT.append("X\n");
            return;
        }
        OUT.append(spans.length() == 0 ? "N" : spans).append('\n');
    }

