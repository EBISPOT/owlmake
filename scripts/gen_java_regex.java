// Writes what owlmake's reading of `java.util.regex` (src/dosdp/java.rs) is
// built and checked against, from the running JDK:
//
//   names      the Unicode block and script names `\p{In\u2026}`, `\p{block=\u2026}` and
//              `\p{script=\u2026}` take, as src/dosdp/java/names.rs;
//   unicode    what `Character` says of each code point: its general category,
//              script and case, the predicates `\p{\u2026}` names, and its type in
//              grapheme segmentation, as src/dosdp/java/unicode.rs;
//   charnames  the character names `\N{\u2026}` takes, deflated, as the file named;
//   cases      tests/fixtures/java-regex/cases.tsv: patterns, inputs and what
//              `Pattern` makes of them.
//
// Run through scripts/gen_java_regex.sh, which writes them all.

