    static void c(String pattern) {
        OUT.append("C\t").append(esc(pattern)).append('\t');
        Pattern p;
        try {
            p = Pattern.compile(pattern);
        } catch (PatternSyntaxException e) {
            OUT.append("E\n");
            return;
        }
        Matcher m = p.matcher("");
        StringBuilder runs = new StringBuilder();
        int count = 0, start = -1;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT + 1; cp++) {
            boolean in = cp <= Character.MAX_CODE_POINT && ALL[cp] != null && m.reset(ALL[cp]).matches();
            if (in) {
                count++;
                if (start < 0) start = cp;
            } else if (start >= 0) {
                runs.append(String.format("%X-%X,", start, cp - 1));
                start = -1;
            }
        }
        long hash = 0xcbf29ce484222325L;
        for (byte b : runs.toString().getBytes(StandardCharsets.US_ASCII)) {
            hash ^= b & 0xff;
            hash *= 0x100000001b3L;
        }
        OUT.append(count).append('\t').append(String.format("%016x", hash)).append('\n');
    }

    static void r(String pattern, String input, String replacement) {
        OUT.append("R\t").append(esc(pattern)).append('\t').append(esc(input)).append('\t')
           .append(esc(replacement)).append('\t');
        try {
            OUT.append(esc(input.replaceFirst(pattern, replacement))).append('\n');
        } catch (RuntimeException e) {
            OUT.append("E\n");
        }
    }

