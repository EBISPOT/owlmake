    static void names() throws Exception {
        Field mapField = Character.UnicodeBlock.class.getDeclaredField("map");
        mapField.setAccessible(true);
        Map<String, Character.UnicodeBlock> map = (Map<String, Character.UnicodeBlock>) mapField.get(null);
        Map<Character.UnicodeBlock, TreeSet<String>> names = new HashMap<>();
        for (Map.Entry<String, Character.UnicodeBlock> e : map.entrySet())
            names.computeIfAbsent(e.getValue(), k -> new TreeSet<>()).add(e.getKey());
        // Each block's code points, in code point order.
        LinkedHashMap<Character.UnicodeBlock, int[]> ranges = new LinkedHashMap<>();
        Character.UnicodeBlock prev = null;
        int start = 0;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT + 1; cp++) {
            Character.UnicodeBlock b = cp <= Character.MAX_CODE_POINT ? Character.UnicodeBlock.of(cp) : null;
            if (b != prev) {
                if (prev != null) {
                    if (ranges.containsKey(prev)) throw new IllegalStateException(prev + " is not one range");
                    ranges.put(prev, new int[] {start, cp - 1});
                }
                prev = b;
                start = cp;
            }
        }
        Field aliasField = Character.UnicodeScript.class.getDeclaredField("aliases");
        aliasField.setAccessible(true);
        Map<String, Character.UnicodeScript> aliases = (Map<String, Character.UnicodeScript>) aliasField.get(null);

        StringBuilder out = new StringBuilder(generated());
        out.append("/// A Unicode block: the name it prints as, every name it goes by in\n");
        out.append("/// `\\p{InName}` and `\\p{block=Name}`, in upper case, and the code points it\n");
        out.append("/// holds (none for a block that holds none).\n");
        out.append("pub(super) type Block = (&'static str, &'static [&'static str], Option<(u32, u32)>);\n\n");
        out.append("/// Every Unicode block.\n");
        out.append("pub(super) const BLOCKS: &[Block] = &[\n");
        List<Character.UnicodeBlock> order = new ArrayList<>(ranges.keySet());
        for (Character.UnicodeBlock b : names.keySet()) if (!ranges.containsKey(b)) order.add(b);
        for (Character.UnicodeBlock b : order) {
            out.append("    (\"").append(b).append("\", &[");
            boolean first = true;
            for (String n : names.get(b)) {
                out.append(first ? "" : ", ").append('"').append(n).append('"');
                first = false;
            }
            int[] r = ranges.get(b);
            if (r == null) out.append("], None),\n");
            else out.append(String.format("], Some((0x%04X, 0x%04X))),\n", r[0], r[1]));
        }
        out.append("];\n\n");
        out.append("/// Each script `\\p{IsName}` and `\\p{script=Name}` name, in the order\n");
        out.append("/// `unicode::SCRIPTS_OF` numbers them: its name, and the other names it goes\n");
        out.append("/// by, in upper case.\n");
        out.append("pub(super) const SCRIPTS: &[(&str, &[&str])] = &[\n");
        for (Character.UnicodeScript s : Character.UnicodeScript.values()) {
            out.append("    (\"").append(s.name()).append("\", &[");
            boolean first = true;
            for (String a : new TreeSet<>(aliasesOf(aliases, s))) {
                out.append(first ? "" : ", ").append('"').append(a).append('"');
                first = false;
            }
            out.append("]),\n");
        }
        out.append("];\n");
        System.out.print(out);
    }

