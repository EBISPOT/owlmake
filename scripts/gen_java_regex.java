    public static void main(String[] args) throws Exception {
        String mode = args.length > 0 ? args[0] : "";
        if (args.length == 1 && mode.equals("names")) names();
        else if (args.length == 1 && mode.equals("unicode")) unicode();
        else if (args.length == 2 && mode.equals("charnames")) charNames(args[1]);
        else if (args.length == 1 && mode.equals("cases")) cases();
        else throw new IllegalArgumentException("usage: names | unicode | charnames FILE | cases");
    }

