//! `template` — generate OWL from a template table (TSV/CSV).
//!
//! Row 1 holds human-readable headers; row 2 holds template strings; rows 3+
//! hold data. Cells that name a class expression are full Manchester syntax and
//! may reference entities by rdfs:label (single-quoted `'foo bar'` or a bare
//! token), CURIE (`OBO:1234`), or full IRI (`<...>`), resolved against a
//! label→IRI index built from the input ontology plus the template's own rows.
//!
//! The template strings owlmake implements. Real templates carry headers beyond
//! this list; one that is not here is unimplemented, and it emits nothing rather
//! than failing — so a component that comes out short is the first sign of it:
//!   `ID`                       the subject IRI (CURIE/IRI/label expanded)
//!   `LABEL`                    rdfs:label; also indexes the subject by label
//!   `TYPE` / `CLASS_TYPE` /    the subject's entity kind (class | object
//!     `PROPERTY_TYPE` /          property | data property | named individual |
//!     `INDIVIDUAL_TYPE`          datatype). Default: class.
//!   class axioms:  `C`/`SC` SubClassOf, `EC` EquivalentTo, `DC` DisjointWith
//!   property axioms: `SP` sub-, `EP` equivalent-, `DP` disjoint-property,
//!                    `DOMAIN`, `RANGE`, `IP` inverse property
//!   characteristics: `CHARACTERISTIC` (functional/transitive/symmetric/...)
//!   individual axioms: `I`/`TI` type (class assertion), `SI` same, `DI` different
//!   annotations: `A <prop>` literal, `AT <prop>^^<dt>` typed,
//!                `AL <prop>@<lang>` language-tagged, `AI <prop>` IRI value
//!   axiom annotations: a header beginning `>` (e.g. `>A <prop>`) annotates the
//!                      axiom generated by the immediately preceding column.
//!   trailing `SPLIT=<c>`       split the cell on `<c>` and apply once per value

